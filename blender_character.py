"""Blender's side of Jarvis's character animation (runs *inside* Blender, loaded with blender_scene.py by
blender_control.with_kit(), so it shares that namespace: helpers here are prefixed _ch_ to never shadow one there).

  character_build(name, template, at, heading)   a rigged, skinned human: a real bone hierarchy (anim_library), IK
                                                 legs and arms with pole targets, feet and hands that copy their
                                                 controls' rotation, a body generated by the Skin modifier and
                                                 weighted bone by bone, clothes coloured by body region
  animate(script)                                anim_core.solve() with the scene's real ground (ray casts on what
                                                 can be walked on), then the result written as keys on the
                                                 controls, the door's hinge and the props; the script is kept on
                                                 the "Jarvis Animation" empty so a follow-up edits it, not rebuilds
  door_facts(build)                              where a build's front door hinges, which way it swings, its size
  inspect_motion()                               what really happens, measured on the evaluated rig every frame:
                                                 feet on the ground and not sliding, IK reaching, the hand on the
                                                 handle, the body clear of walls and the door, knees and elbows
                                                 within their range, no frame that jumps
"""
