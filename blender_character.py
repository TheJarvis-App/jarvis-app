def _ch_anim_root():
    root = bpy.data.objects.get(ANIM_ROOT)
    if root is None:
        root = bpy.data.objects.new(ANIM_ROOT, None)
        bpy.context.scene.collection.objects.link(root)
        root["jarvis_anim"] = "root"
        root.empty_display_size = 0.3
        root.hide_render = True
    return root


