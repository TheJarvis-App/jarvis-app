def _ch_mirror_point(name, p, r):
    return (anim_library.mirror(name), (-p[0], p[1], p[2]), r)


def _ch_body_mesh(name, k, width, hips, build):
    """The body as one smooth skinned surface: a skeleton of points and edges, given flesh by the Skin modifier and
    smoothed by a subdivision, then made a plain mesh."""
    points = []
    for n, p, r in _SKIN:
        points.append((n, p, r))
        if n.endswith(".L"):
            points.append(_ch_mirror_point(n, p, r))
    index = {n: i for i, (n, _, _) in enumerate(points)}
    edges = []
    for a, b in _SKIN_EDGES:
        edges.append((index[a], index[b]))
        if a.endswith(".L") or b.endswith(".L"):
            edges.append((index[anim_library.mirror(a)], index[anim_library.mirror(b)]))

    def scaled(n, p):
        lateral = width if any(s in n for s in ("collar", "shoulder", "biceps", "elbow", "forearm", "wrist", "palm",
                                                 "knuckle", "finger", "thumb")) else hips if any(
            s in n for s in ("hip", "thigh", "knee", "calf", "shin", "ankle", "heel", "ball", "toe")) else 1.0
        return (p[0] * lateral * k, p[1] * k, p[2] * k)

    mesh = bpy.data.meshes.new(name + " skin")
    mesh.from_pydata([scaled(n, p) for n, p, _ in points], edges, [])
    o = bpy.data.objects.new(name + " skin", mesh)
    bpy.context.scene.collection.objects.link(o)
    skin = o.modifiers.new("Skin", 'SKIN')
    skin.use_smooth_shade = True
    sub = o.modifiers.new("Smooth", 'SUBSURF')
    sub.levels = sub.render_levels = 2
    layer = mesh.skin_vertices[0].data
    for i, (n, _, r) in enumerate(points):
        torso = n in ("crotch", "hips", "waist", "chest", "upper")
        f = build if torso else 1.0
        layer[i].radius = (r[0] * k * f, r[1] * k * f)
        layer[i].use_root = (n == "hips")
    bpy.context.view_layer.update()
    deps = bpy.context.evaluated_depsgraph_get()
    body = bpy.data.meshes.new_from_object(o.evaluated_get(deps))
    bpy.data.objects.remove(o, do_unlink=True)
    bpy.data.meshes.remove(mesh)
    return body


def _ch_head_parts(k):
    """Head, hair, nose, ears and eyes: (mesh data, material key) each, already in place."""
    parts = []

    def ellipsoid(at, scale, segments=24, rings=16, keep=None):
        bm = bmesh.new()
        bmesh.ops.create_uvsphere(bm, u_segments=segments, v_segments=rings, radius=1.0)
        for v in bm.verts:
            v.co = Vector((v.co.x * scale[0] * k + at[0] * k, v.co.y * scale[1] * k + at[1] * k,
                           v.co.z * scale[2] * k + at[2] * k))
        if keep is not None:
            gone = [f for f in bm.faces if not keep(f.calc_center_median() / k)]
            bmesh.ops.delete(bm, geom=gone, context='FACES')
        me = bpy.data.meshes.new("part")
        bm.to_mesh(me)
        bm.free()
        for poly in me.polygons:
            poly.use_smooth = True
        return me

    parts.append((ellipsoid((0.0, -0.012, 1.668), (0.087, 0.1, 0.112)), "skin"))
    parts.append((ellipsoid((0.0, -0.045, 1.6), (0.064, 0.066, 0.055)), "skin"))          # jaw and chin
    parts.append((ellipsoid((0.0, -0.108, 1.655), (0.014, 0.022, 0.024), 12, 8), "skin"))  # nose
    for s in (1, -1):
        parts.append((ellipsoid((0.086 * s, -0.005, 1.66), (0.012, 0.022, 0.03), 10, 8), "skin"))
        parts.append((ellipsoid((0.032 * s, -0.093, 1.69), (0.011, 0.008, 0.011), 10, 8), "eyes"))
    parts.append((ellipsoid((0.0, 0.0, 1.69), (0.093, 0.107, 0.104),
                            keep=lambda c: c.z > 1.69 or (c.y > -0.02 and c.z > 1.6)), "hair"))
    return parts


def _ch_join_meshes(meshes):
    """One mesh from several (mesh, material index) pairs, each part's faces keeping its material index."""
    bm = bmesh.new()
    for me, mat_index in meshes:
        tmp = bmesh.new()
        tmp.from_mesh(me)
        for f in tmp.faces:
            f.material_index = mat_index
        offset = len(bm.verts)
        tmp.verts.ensure_lookup_table()
        new_verts = [bm.verts.new(v.co) for v in tmp.verts]
        bm.verts.ensure_lookup_table()
        for f in tmp.faces:
            try:
                nf = bm.faces.new([new_verts[v.index] for v in f.verts])
                nf.material_index = f.material_index
                nf.smooth = f.smooth
            except ValueError:
                pass
        tmp.free()
    out = bpy.data.meshes.new("body")
    bm.to_mesh(out)
    bm.free()
    return out


def _ch_seg_dist(p, a, b):
    ab = b - a
    t = max(0.0, min(1.0, (p - a).dot(ab) / max(ab.length_squared, 1e-12)))
    return (a + ab * t - p).length


def _ch_weights(obj, arm, rigid_from):
    """Vertex groups for every deform bone. Each vertex goes to its nearest bone and blends only with that bone's
    parent or children near a joint — never across the body (inner thigh to the other leg) or to a bone it isn't
    joined to. Vertices from `rigid_from` on (the head parts) belong to the head alone."""
    bones = {b.name: b for b in arm.data.bones if b.use_deform}
    segs = {n: (b.head_local.copy(), b.tail_local.copy()) for n, b in bones.items()}
    family = {}
    for n, b in bones.items():
        fam = {n}
        if b.parent and b.parent.name in bones:
            fam.add(b.parent.name)
        fam.update(c.name for c in b.children if c.name in bones)
        family[n] = fam
    groups = {n: obj.vertex_groups.new(name=n) for n in bones}
    mesh = obj.data
    assigned = {}
    for v in mesh.vertices:
        if v.index >= rigid_from:
            groups["head"].add([v.index], 1.0, 'REPLACE')
            assigned[v.index] = "head"
            continue
        p = v.co
        side = ".L" if p.x > 0.015 else ".R" if p.x < -0.015 else None
        best, best_d = None, 1e9
        dists = {}
        for n, (a, b) in segs.items():
            if side and n[-2:] in (".L", ".R") and n[-2:] != side:
                continue
            if n in ("fingers1.L", "fingers2.L", "fingers1.R", "fingers2.R", "thumb1.L", "thumb2.L", "thumb1.R",
                     "thumb2.R") and p.z > 1.05 * (arm.data.bones["head"].tail_local.z / 1.76):
                continue
            d = _ch_seg_dist(p, a, b)
            dists[n] = d
            if d < best_d:
                best, best_d = n, d
        cands = [n for n in family[best] if n in dists and dists[n] < best_d + 0.05]
        ws = {n: 1.0 / (dists[n] ** 4 + 1e-7) for n in cands}
        tot = sum(ws.values())
        for n, w in ws.items():
            if w / tot > 0.02:
                groups[n].add([v.index], w / tot, 'REPLACE')
        assigned[v.index] = best
    return assigned


def _ch_set_roll(eb, z):
    eb.align_roll(Vector(z))


def character_build(name="Man", template="man", at=(0.0, 0.0, 0.0), heading=0.0):
    """A rigged, skinned human called `name` (removing an earlier one of that name), standing at `at`. Returns
    facts about it: bones, vertices, height, and that every vertex is weighted."""
    t = anim_library.CHARACTERS.get(template, anim_library.CHARACTERS["man"])
    character_remove(name)
    k = t["height"] / anim_library.REST_HEIGHT
    skel = anim_library.skeleton(t["height"], t["width"], t["hips"])
    arm_data = bpy.data.armatures.new(name + " rig")
    arm = bpy.data.objects.new(name, arm_data)
    bpy.context.scene.collection.objects.link(arm)
    _ch_tag(arm, "character", name)
    arm["jarvis_template"] = template
    arm_data.display_type = 'STICK'
    arm.show_in_front = True
    view = bpy.context.view_layer
    prev_active = view.objects.active
    view.objects.active = arm
    bpy.ops.object.mode_set(mode='EDIT')
    ebs = {}
    for n, b in skel.items():
        eb = arm_data.edit_bones.new(n)
        eb.head, eb.tail = Vector(b["head"]), Vector(b["tail"])
        _ch_set_roll(eb, b["z"])
        eb.use_deform = b["deform"]
        ebs[n] = eb
    for n, b in skel.items():
        if b["parent"]:
            ebs[n].parent = ebs[b["parent"]]
            ebs[n].use_connect = (ebs[n].head - ebs[b["parent"]].tail).length < 1e-4 and n not in (
                "hips", "shoulder.L", "shoulder.R", "thigh.L", "thigh.R")
    bpy.ops.object.mode_set(mode='OBJECT')
    view.objects.active = prev_active
    # the rest frames anim_core assumes, checked against what Blender built
    rig = anim_core.Rig(skel)
    worst = 0.0
    for b in arm_data.bones:
        R, _ = rig.rest[b.name]
        m = b.matrix_local
        for i in range(3):
            for j in range(3):
                worst = max(worst, abs(m[i][j] - R[i][j]))
    if worst > 1e-3:
        raise RuntimeError(f"the rig's bone axes differ from the motion solver's ({worst:.4f})")
    # constraints: IK legs and arms, feet and hands turned as their controls
    for s in "LR":
        pb = arm.pose.bones
        ik = pb[f"shin.{s}"].constraints.new('IK')
        ik.target, ik.subtarget = arm, f"foot_ik.{s}"
        ik.pole_target, ik.pole_subtarget = arm, f"knee_pole.{s}"
        ik.chain_count = 2
        ik = pb[f"forearm.{s}"].constraints.new('IK')
        ik.target, ik.subtarget = arm, f"hand_ik.{s}"
        ik.pole_target, ik.pole_subtarget = arm, f"elbow_pole.{s}"
        ik.chain_count = 2
        cr = pb[f"foot.{s}"].constraints.new('COPY_ROTATION')
        cr.target, cr.subtarget = arm, f"foot_ik.{s}"
        cr.name = "Foot rotation"
        cr = pb[f"hand.{s}"].constraints.new('COPY_ROTATION')
        cr.target, cr.subtarget = arm, f"hand_ik.{s}"
        cr.name = "Hand rotation"
        cr.influence = 0.0
        # joints that only bend one way: knees and elbows can't bend backwards
        for bone in (f"shin.{s}", f"forearm.{s}"):
            p = pb[bone]
            p.lock_ik_y = True
    for pb in arm.pose.bones:
        pb.rotation_mode = 'QUATERNION'
    _ch_calibrate_poles(arm)
    # the body
    body_me = _ch_body_mesh(name, k, t["width"], t["hips"], t.get("build", 1.0))
    rigid_from = len(body_me.vertices)
    keys = ["jacket", "trousers", "shoes", "skin", "hair", "eyes"]
    colors = t["colors"]
    mats = {"jacket": _ch_material(f"{name} jacket", colors["jacket"], 0.5, coat=0.25),
            "trousers": _ch_material(f"{name} trousers", colors["trousers"], 0.7),
            "shoes": _ch_material(f"{name} shoes", colors["shoes"], 0.3),
            "skin": _ch_material(f"{name} skin", colors["skin"], 0.48),
            "hair": _ch_material(f"{name} hair", colors["hair"], 0.55),
            "eyes": _ch_material(f"{name} eyes", (0.02, 0.015, 0.012), 0.15)}
    parts = [(body_me, 0)] + [(me, keys.index(key)) for me, key in _ch_head_parts(k)]
    joined = _ch_join_meshes(parts)
    for me, _ in parts:
        bpy.data.meshes.remove(me)
    joined.name = name + " body"
    body = bpy.data.objects.new(name + " body", joined)
    bpy.context.scene.collection.objects.link(body)
    for key in keys:
        joined.materials.append(mats[key])
    _ch_tag(body, "character_body", name)
    body.parent = arm
    assigned = _ch_weights(body, arm, rigid_from)
    for poly in joined.polygons:   # clothes by the bone each face mostly belongs to
        if poly.material_index != 0:
            continue
        owners = [assigned[i] for i in poly.vertices]
        main = max(set(owners), key=owners.count)
        base = main.rsplit(".", 1)[0]
        key = _CLOTHES.get(base, "jacket")
        if base == "hips" and poly.center.z > 0.985 * k:
            key = "jacket"
        if base == "neck" and poly.center.z < arm.data.bones["neck"].head_local.z + 0.035 * k:
            key = "jacket"   # the collar: the neck shows above it, not a patch of skin on the chest
        if base == "forearm" and (poly.center - arm.data.bones[f"forearm{main[-2:]}"].tail_local).length < 0.035 * k:
            key = "skin"
        poly.material_index = keys.index(key)
        poly.use_smooth = True
    mod = body.modifiers.new("Armature", 'ARMATURE')
    mod.object = arm
    mod.use_deform_preserve_volume = True
    arm.location = (0.0, 0.0, 0.0)
    unweighted = sum(1 for v in joined.vertices if not v.groups)
    arm["jarvis_height"] = t["height"]
    _sync()
    return {"name": name, "bones": len(arm.data.bones), "deform": sum(1 for b in arm.data.bones if b.use_deform),
            "vertices": len(joined.vertices), "unweighted": unweighted, "height": round(t["height"], 3),
            "axes_error": round(worst, 6)}


def _ch_calibrate_poles(arm):
    """Blender's IK pole angle depends on the bones' roll: measured here instead of assumed. With each limb bent,
    every candidate angle is tried and the one that points the knee (elbow) straightest at its pole is kept."""
    pb = arm.pose.bones
    for s in "LR":
        for ik_bone, mid, ctrl, pole in ((f"shin.{s}", f"shin.{s}", f"foot_ik.{s}", f"knee_pole.{s}"),
                                         (f"forearm.{s}", f"forearm.{s}", f"hand_ik.{s}", f"elbow_pole.{s}")):
            con = next(c for c in pb[ik_bone].constraints if c.type == 'IK')
            pb[ctrl].location = (0.0, 0.0, 0.0)
            # bend the limb: bring its end toward its root
            pb[ctrl].location = Vector((0.0, 0.18, 0.0)) if "foot" in ctrl else Vector((0.0, 0.15, 0.0))
            best, best_score = 0.0, -1e9
            for deg in (-90.0, 90.0, 0.0, 180.0):
                con.pole_angle = math.radians(deg)
                bpy.context.view_layer.update()
                root = pb[ik_bone].parent.head
                end = pb[ik_bone].tail
                joint = pb[ik_bone].head
                pole_p = pb[pole].head
                line = (end - root).normalized()
                bend = joint - root - line * (joint - root).dot(line)
                towards = pole_p - root - line * (pole_p - root).dot(line)
                score = bend.normalized().dot(towards.normalized()) if bend.length > 1e-4 else -1
                if score > best_score:
                    best, best_score = deg, score
            con.pole_angle = math.radians(best)
            pb[ctrl].location = (0.0, 0.0, 0.0)
    bpy.context.view_layer.update()


def character_remove(name):
    for o in [o for o in bpy.data.objects if o.get("jarvis_owner") == name and o.get("jarvis_anim")]:
        data = o.data
        bpy.data.objects.remove(o, do_unlink=True)
        if data is not None and data.users == 0:
            if isinstance(data, bpy.types.Mesh):
                bpy.data.meshes.remove(data)
            elif isinstance(data, bpy.types.Armature):
                bpy.data.armatures.remove(data)


