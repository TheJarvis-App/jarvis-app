def _ch_role(o):
    return o.get("jarvis_role") or ""


def _ch_is_anim(o):
    return bool(o.get("jarvis_anim"))


def _ch_bvh(objs):
    deps = bpy.context.evaluated_depsgraph_get()
    verts, polys = [], []
    for o in objs:
        ev = o.evaluated_get(deps)
        try:
            me = ev.to_mesh()
        except RuntimeError:
            continue
        m = o.matrix_world
        base = len(verts)
        verts += [m @ v.co for v in me.vertices]
        polys += [[base + i for i in p.vertices] for p in me.polygons]
        ev.to_mesh_clear()
    return BVHTree.FromPolygons(verts, polys) if polys else None


def _ch_walkable():
    out = []
    for o in bpy.context.scene.objects:
        if o.type != 'MESH' or not o.visible_get() or _ch_is_anim(o):
            continue
        role = _ch_role(o)
        if role in _WALKABLE or (not role and not o.get("jarvis_build")):
            out.append(o)
    return out


def _ch_solids(exclude_doors=True):
    out = []
    for o in bpy.context.scene.objects:
        if o.type != 'MESH' or not o.visible_get() or _ch_is_anim(o):
            continue
        role = _ch_role(o)
        if role in ("door",) and exclude_doors:
            continue
        if role in _SOLID or (not role and not o.get("jarvis_build")):
            out.append(o)
    return out


def _ch_clearance_fn(exclude=()):
    """Distance from a point to the nearest solid (walls, frames, furniture; door leaves excluded, they move)."""
    tree = _ch_bvh([o for o in _ch_solids() if o.name not in exclude and _ch_role(o) not in ("slab", "foundation",
                                                                                              "steps", "stairs")])

    def clearance(x, y, z):
        if tree is None:
            return 10.0
        hit = tree.find_nearest(Vector((x, y, z)), 3.0)
        return 3.0 if hit[0] is None else hit[3]
    return clearance


def _ch_ground_fn():
    tree = _ch_bvh(_ch_walkable())

    def ground(x, y, z_hint=None):
        if tree is None:
            return 0.0
        z0 = (z_hint if z_hint is not None else 0.0) + 0.65
        hit = tree.ray_cast(Vector((x, y, z0)), Vector((0, 0, -1)), 4.0)
        if hit[0] is None and z_hint is None:
            hit = tree.ray_cast(Vector((x, y, 3.0)), Vector((0, 0, -1)), 10.0)
        return hit[0].z if hit[0] is not None else 0.0
    return ground


# ---------- doors ----------

def door_facts(build=None, which="front"):
    """The door of `build` (or any build) that the character uses: its leaf, where it hinges (on the side with
    room behind the open leaf, so someone inside can walk it shut), which way it swings and its size."""
    leaves = [o for o in bpy.context.scene.objects if _ch_role(o) == "door" and (build is None or
                                                                                 o.get("jarvis_build") == build)]
    leaves.sort(key=lambda o: (f" door {which} " not in o.name, o.name))
    if not leaves:
        return None
    leaf = leaves[0]
    _sync()
    lo, hi = box(leaf)
    size = hi - lo
    along_x = size.x >= size.y
    mid = (lo + hi) / 2
    width = size.x if along_x else size.y
    thick = size.y if along_x else size.x
    root = bpy.data.objects.get(leaf.get("jarvis_build") or "")
    plan = json.loads(root["jarvis_plan"]) if root is not None and root.get("jarvis_plan") else {}
    # into the building: from the door toward the build's centre
    centre = root.matrix_world.translation if root is not None else Vector((0, 0, 0))
    if along_x:
        n_in = Vector((0, 1 if centre.y > mid.y else -1, 0))
        ends = [Vector((lo.x, mid.y, lo.z)), Vector((hi.x, mid.y, lo.z))]
    else:
        n_in = Vector((1 if centre.x > mid.x else -1, 0, 0))
        ends = [Vector((mid.x, lo.y, lo.z)), Vector((mid.x, hi.y, lo.z))]
    solids = _ch_bvh([o for o in _ch_solids() if o is not leaf])
    room = []
    for end in ends:
        other = ends[1] if end is ends[0] else ends[0]
        away = (end - other).normalized()
        start = end + n_in * 0.9 + Vector((0, 0, 1.2))
        hit = solids.ray_cast(start, away, 4.0) if solids else (None,)
        room.append(4.0 if hit[0] is None else (hit[0] - start).length)
    hinge_i = 0 if room[0] >= room[1] else 1
    hinge = ends[hinge_i]
    u = (ends[1 - hinge_i] - hinge).normalized()
    return {"id": which, "leaf": leaf.name, "hinge": [round(hinge.x, 4), round(hinge.y, 4), round(lo.z, 4)],
            "u": [round(u.x, 4), round(u.y, 4)], "n_in": [round(n_in.x, 4), round(n_in.y, 4)],
            "width": round(width, 4), "height": round(size.z, 4), "thick": round(thick, 4),
            "room_behind": [round(r, 2) for r in room], "build": leaf.get("jarvis_build"),
            "floor_inside": plan.get("plinth", 0.35) + plan.get("slab", 0.2) if plan else round(lo.z, 3)}


def _ch_door_rig(facts):
    """The leaf hangs from a hinge (an empty at its edge) and gets lever handles on both faces; the hinge's turn is
    what's keyed. Made once; a later run reuses it."""
    leaf = bpy.data.objects[facts["leaf"]]
    name = f"{facts['leaf']} hinge"
    hinge = bpy.data.objects.get(name)
    if hinge is None:
        hinge = bpy.data.objects.new(name, None)
        bpy.context.scene.collection.objects.link(hinge)
        _ch_tag(hinge, "hinge", facts["id"])
        hinge.empty_display_type = 'SINGLE_ARROW'
        hinge.empty_display_size = 0.3
    _sync()
    world = leaf.matrix_world.copy()
    if hinge.animation_data:
        hinge.animation_data_clear()
    hinge.parent = leaf.parent
    hinge.matrix_parent_inverse = leaf.parent.matrix_world.inverted() if leaf.parent else Matrix()
    hinge.matrix_world = Matrix.Translation(Vector(facts["hinge"]))
    _sync()
    if leaf.parent is not hinge:
        leaf.parent = hinge
        leaf.matrix_parent_inverse = hinge.matrix_world.inverted()
        leaf.matrix_world = world
    _sync()
    handle_mat = _ch_material("Door handle", (0.75, 0.74, 0.7), 0.25, metallic=1.0)
    u = Vector((facts["u"][0], facts["u"][1], 0))
    n_in = Vector((facts["n_in"][0], facts["n_in"][1], 0))
    d = anim_library.ACTIONS["door"]
    for inner in (True, False):
        hname = f"{facts['leaf']} handle {'inside' if inner else 'outside'}"
        h = bpy.data.objects.get(hname)
        if h is not None:
            bpy.data.objects.remove(h, do_unlink=True)
        bm = bmesh.new()
        lever = 0.12
        # a rose on the face and a lever pointing back toward the hinge
        bmesh.ops.create_cube(bm, size=1.0, matrix=Matrix.Diagonal((0.05, 0.05, 0.05, 1.0)))
        geom = bmesh.ops.create_cube(bm, size=1.0, matrix=Matrix.Translation((0.0, -lever / 2 + 0.02, 0.0)) @
                                     Matrix.Diagonal((0.022, lever, 0.022, 1.0)))
        me = bpy.data.meshes.new(hname)
        bm.to_mesh(me)
        bm.free()
        h = bpy.data.objects.new(hname, me)
        bpy.context.scene.collection.objects.link(h)
        me.materials.append(handle_mat)
        _ch_tag(h, "handle", facts["id"])
        side = n_in if inner else -n_in
        at = Vector(facts["hinge"]) + u * (facts["width"] - d["handle_in"]) + side * (facts["thick"] / 2 + 0.025)
        at.z = facts["hinge"][2] + d["handle_height"]
        # local y of the lever points from the handle toward the hinge
        y = -u
        z = Vector((0, 0, 1))
        x = y.cross(z)
        h.matrix_world = Matrix.Translation(at) @ Matrix((x, y, z)).transposed().to_4x4()
        h.parent = leaf
        h.matrix_parent_inverse = leaf.matrix_world.inverted()
        h.matrix_world = Matrix.Translation(at) @ Matrix((x, y, z)).transposed().to_4x4()
    return hinge


def _ch_bind(obj, action):
    """Make `obj` play `action`. Since Blender 4.4 an action's keys live in a slot that the object must name too:
    an action assigned while it was still empty is left with no slot bound, and plays nothing."""
    obj.animation_data_create()
    obj.animation_data.action = action
    ad = obj.animation_data
    if hasattr(ad, "action_slot") and ad.action_slot is None and len(action.slots):
        ad.action_slot = action.slots[0]


def _ch_key_prop(name, prop, frames):
    """A prop's solved transforms as keys on its object: held still before it's taken and after it's put down."""
    o = bpy.data.objects.get(name)
    if o is None or not prop["keys"]:
        return
    o.animation_data_clear()
    o.rotation_mode = 'QUATERNION'
    action = bpy.data.actions.new(f"{name} handled")
    loc = [action.fcurves.new("location", index=i, action_group="Handled") for i in range(3)]
    rot = [action.fcurves.new("rotation_quaternion", index=i, action_group="Handled") for i in range(4)]
    keys = sorted((int(f), v) for f, v in prop["keys"].items())
    start = prop["start"]
    rows = [(0, start)] + keys
    cur = start
    full = []
    j = 0
    for f in range(0, frames):
        while j < len(rows) and rows[j][0] <= f:
            cur = rows[j][1]
            j += 1
        full.append((f, cur))
    for i in range(3):
        loc[i].keyframe_points.add(len(full))
        loc[i].keyframe_points.foreach_set("co", [c for f, (R, t) in full for c in (f + 1, t[i])])
        loc[i].update()
    for i in range(4):
        rot[i].keyframe_points.add(len(full))
        rot[i].keyframe_points.foreach_set("co", [c for f, (R, t) in full for c in (f + 1, anim_core.quat(R)[i])])
        rot[i].update()
    _ch_bind(o, action)


def _ch_key_hinge(hinge, facts, angles, sign):
    hinge.rotation_mode = 'XYZ'
    hinge.animation_data_create()
    hinge.animation_data.action = None
    action = bpy.data.actions.new(f"{hinge.name} swing")
    fc = action.fcurves.new("rotation_euler", index=2, action_group="Door")
    frames = sorted(angles)
    fc.keyframe_points.add(len(frames))
    fc.keyframe_points.foreach_set("co", [c for f in frames for c in (f + 1, sign * math.radians(angles[f]))])
    for kp in fc.keyframe_points:
        kp.interpolation = 'LINEAR'
    fc.update()
    _ch_bind(hinge, action)


# ---------- writing the motion ----------

def _ch_write_action(arm, actor):
    arm.animation_data_create()
    if arm.animation_data.action is not None:
        old = arm.animation_data.action
        arm.animation_data.action = None
        if old.users == 0:
            bpy.data.actions.remove(old)
    action = bpy.data.actions.new(f"{arm.name} motion")
    bones = actor["bones"]
    for name, frames in bones.items():
        pb = arm.pose.bones.get(name)
        if pb is None:
            continue
        n = len(frames)
        paths = []
        if name in anim_library.CONTROLS:
            paths.append(("location", 3, lambda fr, i: fr[0][i]))
        paths.append(("rotation_quaternion", 4, lambda fr, i: fr[1][i]))
        for prop, count, get in paths:
            for i in range(count):
                fc = action.fcurves.new(f'pose.bones["{name}"].{prop}', index=i, action_group=name)
                fc.keyframe_points.add(n)
                fc.keyframe_points.foreach_set("co", [c for f in range(n) for c in (f + 1, get(frames[f], i))])
                fc.update()
    for key, values in actor["influences"].items():
        side = key[-1]
        fc = action.fcurves.new(f'pose.bones["hand.{side}"].constraints["Hand rotation"].influence', index=0,
                                action_group=f"hand.{side}")
        fc.keyframe_points.add(len(values))
        fc.keyframe_points.foreach_set("co", [c for f, v in enumerate(values) for c in (f + 1, v)])
        fc.update()
    _ch_bind(arm, action)
    return action


def animate(script):
    """Solve `script` (anim_core's format; the door may be given as {"door": "front"} and is looked up in the
    scene) on the real ground and write it into Blender: characters (built when missing), the door's swing, the
    props. Returns what happened, frame by frame facts kept for inspect_motion()."""
    if isinstance(script, str):
        script = json.loads(script)
    scene = bpy.context.scene
    doors = []
    for d in script.get("doors", []):
        facts = door_facts(d.get("build"), d.get("id", "front")) if "hinge" not in d else d
        if facts is None:
            raise RuntimeError("there's no door in the scene to open")
        facts.update({k: v for k, v in d.items() if k in ("hinge", "u", "n_in")})
        doors.append(facts)
    for facts in doors:   # a re-run starts from the door as it hangs closed
        hinge = bpy.data.objects.get(f"{facts['leaf']} hinge")
        if hinge is not None and hinge.animation_data:
            hinge.animation_data_clear()
            hinge.rotation_euler = (0, 0, 0)
    _sync()
    ground = _ch_ground_fn()
    held = [p["id"] for p in script.get("props", [])]
    clearance = _ch_clearance_fn(exclude=[d["leaf"] for d in doors] + held + [s["id"] for s in script.get("seats", [])])
    solved = anim_core.solve(dict(script, doors=doors), ground, clearance=clearance)
    made = {}
    for spec in script.get("actors", []):
        name = spec.get("name") or spec["id"].title()
        arm = bpy.data.objects.get(name)
        if arm is None or arm.get("jarvis_anim") != "character" or arm.get("jarvis_template") != spec.get(
                "template", "man"):
            made[name] = character_build(name, spec.get("template", "man"))
            arm = bpy.data.objects[name]
        _ch_write_action(arm, solved["actors"][spec["id"]])
        arm["jarvis_actor"] = spec["id"]
    for facts in doors:
        hinge = _ch_door_rig(facts)
        sign = 1.0 if (Vector((facts["u"][0], facts["u"][1], 0)).cross(
            Vector((facts["n_in"][0], facts["n_in"][1], 0)))).z > 0 else -1.0
        _ch_key_hinge(hinge, facts, solved["doors"][facts["id"]] or {0: 0.0}, sign)
    for pid, prop in solved["props"].items():   # what hands carry moves with them
        _ch_key_prop(pid, prop, solved["frames"])
    scene.frame_start = 1
    scene.frame_end = max(scene.frame_end if scene.frame_end > 1 else 0, solved["frames"])
    scene.render.fps = anim_library.FPS
    root = _ch_anim_root()
    root["jarvis_script"] = json.dumps(script)
    root["jarvis_events"] = json.dumps({a: v["events"] for a, v in solved["actors"].items()})
    root["jarvis_doors"] = json.dumps(doors)
    _sync()
    return {"frames": solved["frames"], "built": made,
            "events": {a: [(e["what"], e["frame"] + 1) for e in v["events"]] for a, v in solved["actors"].items()},
            "doors": [d["leaf"] for d in doors], "door_max": {d["id"]: round(max(solved["doors"][d["id"]].values()), 1)
                                                               if solved["doors"][d["id"]] else 0 for d in doors}}


# ---------- what really happens, measured ----------

def _ch_pose_point(arm, bone, local):
    pb = arm.pose.bones[bone]
    return arm.matrix_world @ (pb.matrix @ Vector(local))


def inspect_motion(step=1):
    """Every character, every `step` frames, measured on the evaluated rig and scene: {character: facts}."""
    scene = bpy.context.scene
    root = bpy.data.objects.get(ANIM_ROOT)
    if root is None:
        return {"error": "there's no animation in the scene"}
    events = json.loads(root.get("jarvis_events", "{}"))
    doors = json.loads(root.get("jarvis_doors", "[]"))
    chars = [o for o in scene.objects if o.get("jarvis_anim") == "character"]
    keep = scene.frame_current
    ground = _ch_ground_fn()
    script = json.loads(root.get("jarvis_script", "{}"))
    handled = {p["id"] for p in script.get("props", [])}
    solids_static = _ch_bvh([o for o in _ch_solids() if not any(o.name == d["leaf"] for d in doors) and
                             o.name not in handled])
    out = {"frames": [scene.frame_start, scene.frame_end], "characters": {}}
    for arm in chars:
        k = arm.get("jarvis_height", 1.78) / anim_library.REST_HEIGHT
        ev = events.get(arm.get("jarvis_actor", ""), [])
        holds = []   # (start, end, door id) of each hold on a handle
        carries = []   # (start, end, prop, hand) of each thing held
        start = None
        took = {}
        for e in ev:
            if e["what"] == "grasp handle":
                start = (e["frame"] + 1, e.get("door"), e.get("hand"))
            elif e["what"] == "release handle" and start:
                holds.append((start[0], e["frame"] + 1, start[1], start[2]))
                start = None
            elif e["what"] == "grasp" and e.get("prop"):
                took[e["prop"]] = (e["frame"] + 1, e.get("hand", "R"))
            elif e["what"] == "release" and e.get("prop") in took:
                f0, hand = took.pop(e["prop"])
                carries.append((f0, e["frame"] + 1, e["prop"], hand))
        for prop, (f0, hand) in took.items():
            carries.append((f0, scene.frame_end, prop, hand))
        facts = {"slide": 0.0, "float": 0.0, "sink": 0.0, "ik_leg": 0.0, "ik_arm": 0.0, "hand_handle": 0.0,
                 "hand_prop": 0.0, "carry_frames": 0,
                 "hold_frames": 0, "wall_hits": [], "door_hits": [], "knee": [999.0, -999.0],
                 "elbow": [999.0, -999.0], "knee_backwards": 0, "jump_deg": 0.0, "jump_where": None,
                 "frames_measured": 0}
        planted_prev = {}
        last_ankle = {}
        prev_mats = None
        # where the sole is, in each foot bone's own space (from the rest pose): heel and ball under the foot,
        # the toe tip under the toe bone, so a heel raised on bent toes is measured as it really is
        sole_local = {}
        for s in "LR":
            foot, toe = arm.data.bones[f"foot.{s}"], arm.data.bones[f"toe.{s}"]
            a_ = foot.head_local
            fwd_rest = Vector((0, -1, 0))
            pts = {"heel": ("foot", a_ + fwd_rest * (anim_library.HEEL * k) - Vector((0, 0, anim_library.ANKLE * k))),
                   "ball": ("foot", a_ + fwd_rest * (anim_library.BALL * k) - Vector((0, 0, anim_library.ANKLE * k))),
                   "toe": ("toe", a_ + fwd_rest * (anim_library.TOE * k) - Vector((0, 0, anim_library.ANKLE * k)))}
            sole_local[s] = {key: (f"{b}.{s}", arm.data.bones[f"{b}.{s}"].matrix_local.inverted() @ p)
                             for key, (b, p) in pts.items()}
        rest_dir = (arm.data.bones["foot.L"].tail_local - arm.data.bones["foot.L"].head_local).normalized()
        rest_slope = rest_dir.z
        for f in range(scene.frame_start, scene.frame_end + 1, step):
            scene.frame_set(f)
            pb = arm.pose.bones
            mw = arm.matrix_world
            facts["frames_measured"] += 1
            for s in "LR":
                # feet: the sole's heel, ball and toe tip, carried by the evaluated foot and toe bones
                ankle = mw @ pb[f"foot.{s}"].head
                target = mw @ pb[f"foot_ik.{s}"].head
                facts["ik_leg"] = max(facts["ik_leg"], (ankle - target).length)
                soles = {key: mw @ (pb[bone].matrix @ local) for key, (bone, local) in sole_local[s].items()}
                fwd = (mw.to_3x3() @ (pb[f"foot.{s}"].matrix.to_3x3() @ Vector((0, 1, 0)))).normalized()
                flat = abs(fwd.z - rest_slope) < 0.035
                g = ground(ankle.x, ankle.y, ankle.z - 0.2)
                lowest = min(p.z - ground(p.x, p.y, ankle.z - 0.2) for p in soles.values())
                here = Vector((ankle.x, ankle.y, ankle.z))
                was = last_ankle.get(s)
                last_ankle[s] = here
                # planted: flat and (nearly) still; a level foot passing mid-swing is not standing on anything
                planted = flat and was is not None and (here - was).length < 0.003 * step
                if planted:
                    gap = min(soles["heel"].z, soles["ball"].z) - g
                    if gap > facts["float"]:
                        facts["float"], facts["float_at"] = gap, (f, s)
                    if s in planted_prev:
                        facts["slide"] = max(facts["slide"], (Vector((ankle.x, ankle.y)) -
                                                              planted_prev[s]).length)
                    planted_prev[s] = Vector((ankle.x, ankle.y))
                else:
                    planted_prev.pop(s, None)
                if -lowest > facts["sink"]:
                    facts["sink"], facts["sink_at"] = -lowest, (f, s, min(soles, key=lambda q: soles[q].z -
                                                                          ground(soles[q].x, soles[q].y,
                                                                                 ankle.z - 0.2)))
                wrist = mw @ pb[f"hand.{s}"].head
                facts["ik_arm"] = max(facts["ik_arm"], (wrist - mw @ pb[f"hand_ik.{s}"].head).length)
                # knee and elbow bend, and which way the knee points
                for joint, a, b, key in ((f"shin.{s}", f"thigh.{s}", f"shin.{s}", "knee"),
                                         (f"forearm.{s}", f"upper_arm.{s}", f"forearm.{s}", "elbow")):
                    v1 = pb[a].tail - pb[a].head
                    v2 = pb[b].tail - pb[b].head
                    ang = math.degrees(v1.angle(v2)) if v1.length and v2.length else 0.0
                    facts[key][0] = min(facts[key][0], ang)
                    facts[key][1] = max(facts[key][1], ang)
                knee = mw @ pb[f"shin.{s}"].head
                hip = mw @ pb[f"thigh.{s}"].head
                line = (ankle - hip)
                if line.length > 1e-6 and (knee - hip).length > 1e-6:
                    off = (knee - hip) - line.normalized() * (knee - hip).dot(line.normalized())
                    if off.length > 0.01 and off.normalized().dot(Vector((fwd.x, fwd.y, 0)).normalized()) < -0.2:
                        facts["knee_backwards"] += 1
            # the hand on the handle while it holds it
            for h0, h1, door_id, hand in holds:
                if h0 <= f < h1:
                    door = next((d for d in doors if d["id"] == door_id), None)
                    if door:
                        names = [f"{door['leaf']} handle inside", f"{door['leaf']} handle outside"]
                        palm = mw @ (pb[f"hand.{hand}"].matrix @ Vector((0, 0.045 * k, 0)))
                        wrist = mw @ pb[f"hand.{hand}"].head
                        dist = min(min((bpy.data.objects[n].matrix_world.translation - p).length for p in (palm, wrist))
                                   for n in names if n in bpy.data.objects)
                        facts["hand_handle"] = max(facts["hand_handle"], dist)
                        facts["hold_frames"] += 1
            # the hand on what it carries: the palm within reach of the thing's own surface
            for h0, h1, prop, hand in carries:
                o = bpy.data.objects.get(prop)
                if o is not None and h0 <= f < h1:
                    palm = mw @ (pb[f"hand.{hand}"].matrix @ Vector((0, 0.045 * k, 0)))
                    lo, hi = box(o)
                    near = Vector([min(max(palm[i], lo[i]), hi[i]) for i in range(3)])
                    facts["hand_prop"] = max(facts["hand_prop"], (near - palm).length)
                    facts["carry_frames"] += 1
            # the body clear of walls (and of the door leaf, wherever it has swung to)
            leaf_trees = [(d["id"], _ch_bvh([bpy.data.objects[d["leaf"]]])) for d in doors]
            for bone, radius in anim_library.BODY_CAPSULES.items():
                for s in ("L", "R") if bone in ("thigh", "shin", "upper_arm", "forearm") else ("",):
                    name = f"{bone}.{s}" if s else bone
                    a = mw @ pb[name].head
                    b = mw @ pb[name].tail
                    for i in range(4):
                        p = a.lerp(b, (i + 0.5) / 4)
                        r = radius * k
                        if solids_static:
                            hit = solids_static.find_nearest(p, r * 0.8)
                            if hit[0] is not None and name not in ("shin.L", "shin.R"):
                                facts["wall_hits"].append((f, name, round(r - hit[3], 3)))
                        for did, tree in leaf_trees:
                            if tree:
                                hit = tree.find_nearest(p, r * 0.8)
                                if hit[0] is not None:
                                    facts["door_hits"].append((f, name, round(r - hit[3], 3)))
            # no frame where a bone jumps
            mats = {b.name: (mw @ b.matrix).to_quaternion() for b in pb if b.bone.use_deform}
            if prev_mats is not None:
                for n, q in mats.items():
                    ang = math.degrees(q.rotation_difference(prev_mats[n]).angle)
                    ang = min(ang, 360 - ang)
                    if ang > facts["jump_deg"]:
                        facts["jump_deg"], facts["jump_where"] = round(ang, 1), (f, n)
            prev_mats = mats
        facts["wall_hits"] = facts["wall_hits"][:12]
        facts["door_hits"] = facts["door_hits"][:12]
        for key in ("slide", "float", "sink", "ik_leg", "ik_arm", "hand_handle", "hand_prop"):
            facts[key] = round(facts[key], 4)
        facts["knee"] = [round(v, 1) for v in facts["knee"]]
        facts["elbow"] = [round(v, 1) for v in facts["elbow"]]
        out["characters"][arm.name] = facts
    door_out = {}
    for d in doors:
        hinge = bpy.data.objects.get(f"{d['leaf']} hinge")
        if hinge is not None:
            vals = []
            for f in range(scene.frame_start, scene.frame_end + 1):
                scene.frame_set(f)
                vals.append(abs(math.degrees(hinge.matrix_world.to_euler().z - hinge.parent.matrix_world.to_euler().z
                                             if hinge.parent else hinge.matrix_world.to_euler().z)))
            door_out[d["id"]] = {"max": round(max(vals), 1), "end": round(vals[-1], 2),
                                 "max_step": round(max(abs(a - b) for a, b in zip(vals, vals[1:])), 2)}
    out["doors"] = door_out
    scene.frame_set(keep)
    return out
